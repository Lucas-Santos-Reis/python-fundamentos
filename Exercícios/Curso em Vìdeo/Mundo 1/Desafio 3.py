#Faça um script Python que leia dois números e mostre a soma entre eles.
n1 = int(input('Digite o primeiro número: ')) #tem que converter para inteiro
n2 = int(input('Digite o segundo número: ')) #tem que converter para inteiro
soma = n1 + n2 #realiza a soma
print(f'A soma entre {n1} e {n2} é igual a {soma}.') #mostra o resultado